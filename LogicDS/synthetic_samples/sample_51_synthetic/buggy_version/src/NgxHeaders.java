public class NgxHeaders {

    public NgxStr user = new NgxStr();
    public NgxStr authorization = new NgxStr();

    public NgxStr getUser() { return user; }
    public void setUser(NgxStr user) { this.user = user; }

    public NgxStr getAuthorization() { return authorization; }
    public void setAuthorization(NgxStr authorization) { this.authorization = authorization; }
}
